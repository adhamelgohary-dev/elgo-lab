#!/usr/bin/env node
/**
 * Generate `backend/answer-key.js` from canonical `content/subjects/*.json`.
 *
 * Exports:
 *   { generatedAt, totalQuestions, TOTAL_QUESTIONS, collections, byInternalId, byOriginalId }
 */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SUBJECTS_DIR = path.join(ROOT, "content", "subjects");
const OUT_FILE = path.join(ROOT, "backend", "answer-key.js");

function loadSubjects() {
  if (!fs.existsSync(SUBJECTS_DIR)) {
    throw new Error(`Missing subjects directory: ${SUBJECTS_DIR}`);
  }
  const files = fs.readdirSync(SUBJECTS_DIR)
    .filter((f) => f.endsWith(".json") && !f.startsWith("."))
    .sort();
  return files.map((file) => {
    const raw = fs.readFileSync(path.join(SUBJECTS_DIR, file), "utf8");
    return JSON.parse(raw);
  });
}

function buildAnswerKey() {
  const subjects = loadSubjects();
  const collections = {};
  const byInternalId = {};
  const byOriginalId = {};
  let totalQuestions = 0;

  function registerCollection(subjectId, col, sourceType, questions) {
    if (!col || !col.id) return;
    const list = Array.isArray(questions) ? questions : [];
    const key = `${subjectId}::${col.id}`;
    const answers = {};
    const ungradableIds = [];
    let gradableQuestions = 0;

    list.forEach((q, idx) => {
      if (!q || !q.id) return;
      totalQuestions += 1;
      const internalId = q.internalId || `${subjectId}::${sourceType}::${col.id}::${q.id}`;
      const ans = q.correctOptionId != null ? String(q.correctOptionId).trim().toUpperCase() : "";
      if (ans) {
        gradableQuestions += 1;
        answers[internalId] = ans;
        answers[q.id] = ans;
        byInternalId[internalId] = {
          correctOptionId: ans,
          subjectId,
          collectionId: col.id,
          sourceType,
          index: idx,
        };
        byOriginalId[q.id] = {
          internalId,
          correctOptionId: ans,
          subjectId,
          collectionId: col.id,
          sourceType,
        };
      } else {
        ungradableIds.push(internalId);
        if (q.id) ungradableIds.push(String(q.id));
      }
    });

    collections[key] = {
      subjectId,
      collectionId: col.id,
      sourceType,
      totalQuestions: list.length,
      gradableQuestions,
      answers,
      ungradableIds,
    };
  }

  for (const subj of subjects) {
    if (!subj || !subj.id) continue;
    (subj.quizzes || []).forEach((qCol) => registerCollection(subj.id, qCol, "quiz", qCol.questions));
    (subj.lectures || []).forEach((lec) => {
      const qs = (lec.generatedQuiz && lec.generatedQuiz.questions) || [];
      registerCollection(subj.id, lec, "lecture", qs);
    });
    (subj.sheets || []).forEach((sh) => registerCollection(subj.id, sh, "sheet", sh.questions));
  }

  return {
    generatedAt: new Date().toISOString(),
    totalQuestions,
    TOTAL_QUESTIONS: totalQuestions,
    collections,
    byInternalId,
    byOriginalId,
  };
}

function writeAnswerKey(outPath) {
  const key = buildAnswerKey();
  const target = outPath || OUT_FILE;
  const content =
    `"use strict";\n` +
    `/* AUTO-GENERATED by tools/build-answer-key.js — DO NOT EDIT BY HAND */\n` +
    `module.exports = ${JSON.stringify(key, null, 2)};\n`;
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, content, "utf8");
  return key;
}

if (require.main === module) {
  const key = writeAnswerKey();
  console.log(`Generated backend/answer-key.js: ${Object.keys(key.collections).length} collections, ${key.totalQuestions} questions.`);
}

module.exports = { buildAnswerKey, writeAnswerKey };
